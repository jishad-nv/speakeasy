    val all300Phrases: List<ZeroSurvivalPhrase> by lazy {
        val out = mutableListOf<ZeroSurvivalPhrase>()
        var num = 1
        fun append(cat: ZeroPhraseCategory, list: List<PhraseSeed>) {
            list.forEach { seed ->
                out.add(
                    ZeroSurvivalPhrase(
                        id = "zero_${cat.id}_$num",
                        category = cat,
                        englishText = seed.en,
                        malayalamMeaning = seed.ml,
                        manglishScript = seed.manglish,
                        numberTag = num++
                    )
                )
            }
        }
        append(ZeroPhraseCategory.GREETINGS, greetingsBase)
        append(ZeroPhraseCategory.NUMBERS, numbersBase)
        append(ZeroPhraseCategory.FAMILY, familyBase)
        append(ZeroPhraseCategory.FOOD, foodBase)
        append(ZeroPhraseCategory.DAILY_ROUTINE, routineBase)
        out
    }

    fun byCategory(category: ZeroPhraseCategory): List<ZeroSurvivalPhrase> =
        all300Phrases.filter { it.category == category }
